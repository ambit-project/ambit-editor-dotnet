    [Fact]
    public void ExtractsSymbols_IncludingCSharp15Unions()
    {
        var symbols = SymbolExtractor.Extract("""
            namespace Shop.Orders;
            public union Payment(Card, Cash);
            public sealed class OrderService
            {
                const int Max = 10;
                private readonly int count, total;
                public string Name { get; set; } = "";
                public OrderService() { }
                public void Place(int id) { }
                public event EventHandler? Placed;
                public enum State { New, Paid }
            }
            public interface IOrderRepository { Task SaveAsync(); }
            public record struct Money(decimal Amount);
            """);
        string Describe(IndexedSymbol s) => $"{s.Kind}:{s.Container}.{s.Name}";
        var all = symbols.Select(Describe).ToList();
        Assert.Contains("namespace:.Shop.Orders", all);
        Assert.Contains("union:Shop.Orders.Payment", all);
        Assert.Contains("class:Shop.Orders.OrderService", all);
        Assert.Contains("constant:Shop.Orders.OrderService.Max", all);
        Assert.Contains("field:Shop.Orders.OrderService.total", all);
        Assert.Contains("property:Shop.Orders.OrderService.Name", all);
        Assert.Contains("constructor:Shop.Orders.OrderService.OrderService", all);
        Assert.Contains("method:Shop.Orders.OrderService.Place", all);
        Assert.Contains("event:Shop.Orders.OrderService.Placed", all);
        Assert.Contains("enum:Shop.Orders.OrderService.State", all);
        Assert.Contains("enum member:Shop.Orders.OrderService.State.Paid", all);
        Assert.Contains("interface:Shop.Orders.IOrderRepository", all);
        Assert.Contains("method:Shop.Orders.IOrderRepository.SaveAsync", all);
        Assert.Contains("record struct:Shop.Orders.Money", all);
        Assert.Equal(9, symbols.Single(s => s.Name == "Place").Line);
    }

    [Fact]
    public async Task IndexesSearchesAndUpdatesIncrementally()
    {
        using var dir = new TempDir();
        var ct = TestContext.Current.CancellationToken;
        dir.Write("src/Shop/Shop.csproj", "<Project Sdk=\"Microsoft.NET.Sdk\" />");
        var controller = dir.Write("src/Shop/Controllers/UserController.cs", """
            namespace Shop.Controllers;
            public class UserController
            {
                public string GetUserName() => "ConnectionString_Value";
            }
            """);
        dir.Write("src/Shop/obj/Debug/Generated.cs", "class ShouldNotBeIndexed {}");
        dir.Write("src/Shop/Models/Order.g.cs", "class GeneratedOrder {}");
        dir.Write("src/Shop/Models/Order.cs", "// <auto-generated/>\nclass AutoGenerated {}");
        dir.Write("src/Shop/appsettings.json", """{ "ConnectionStrings": { "Db": "Host=localhost" } }""");

        var dbPath = Path.Combine(dir.Path, ".index.db");
        using var db = new IndexDatabase(dbPath);
        using var indexer = new FileIndexer(db, dir.Path, new IndexOptions(), NullLogger.Instance);
        await indexer.SynchronizeAsync(force: false, ct);
        var search = new SearchService(dbPath, dir.Path);

        // Quick open: substring, fuzzy, project name
        var hit = search.QuickOpen("UserCon", ct: ct)[0];
        Assert.Equal("UserController.cs", hit.Name);
        Assert.Equal("Shop", hit.Project);
        Assert.Equal("UserController.cs", search.QuickOpen("usrctl", ct: ct)[0].Name);
        Assert.DoesNotContain(search.QuickOpen("Generated", ct: ct), h => h.Name == "Generated.cs");

        // Symbols
        Assert.Equal("UserController", search.Symbols("UserController", ct: ct)[0].Name);
        var method = Assert.Single(search.Symbols("UserController.GetUser", ct: ct));
        Assert.Equal(4, method.Line);
        Assert.Empty(search.Symbols("ShouldNotBeIndexed", ct: ct));
        Assert.Empty(search.Symbols("GeneratedOrder", ct: ct));
        Assert.Empty(search.Symbols("AutoGenerated", ct: ct));

        // Full text, case-insensitive by default; json is indexed too
        var text = search.FullText("connectionstring", new TextSearchOptions(), ct);
        Assert.Equal(2, text.Count);
        Assert.Single(search.FullText("ConnectionStrings", new TextSearchOptions(MatchCase: true, WholeWord: true), ct));

        // Modify: new symbol appears, old one disappears
        File.WriteAllText(controller, "namespace Shop.Controllers;\npublic class AccountController { }\n");
        File.SetLastWriteTimeUtc(controller, DateTime.UtcNow.AddSeconds(5));
        await indexer.SynchronizeAsync(force: false, ct);
        Assert.Empty(search.Symbols("UserController", ct: ct));
        Assert.Single(search.Symbols("AccountController", ct: ct));

        // Delete
        File.Delete(controller);
        await indexer.SynchronizeAsync(force: false, ct);
        Assert.Empty(search.Symbols("AccountController", ct: ct));
        Assert.Empty(search.FullText("AccountController", new TextSearchOptions(), ct));

        // Persisted: a new connection sees the same data, and a no-op sync touches nothing
        var (files, _) = search.Stats();
        Assert.Equal(3, files); // csproj, json, Order.cs (Order.g.cs and obj/ are skipped)
    }

    [Fact]
    public async Task WatcherPicksUpNewFiles()
    {
        using var dir = new TempDir();
        var ct = TestContext.Current.CancellationToken;
        var dbPath = Path.Combine(dir.Path, ".index.db");
        using var db = new IndexDatabase(dbPath);
        using var indexer = new FileIndexer(db, dir.Path, new IndexOptions { WatcherDebounceMs = 50 }, NullLogger.Instance);
        await indexer.SynchronizeAsync(false, ct);
        var updated = new TaskCompletionSource();
        indexer.Updated += () => updated.TrySetResult();
        indexer.StartWatching();

        dir.Write("Later.cs", "class LaterAddedType {}");
        await updated.Task.WaitAsync(TimeSpan.FromSeconds(10), ct);
        Assert.Single(new SearchService(dbPath, dir.Path).Symbols("LaterAddedType", ct: ct));
    }

    [Theory]
    [InlineData("oc", "OrderController.cs", true)]
    [InlineData("OrdCon", "OrderController.cs", true)]
    [InlineData("xyz", "OrderController.cs", false)]
    public void FuzzyMatcher_Matches(string query, string candidate, bool expected) =>
        Assert.Equal(expected, FuzzyMatcher.Score(query, candidate) is not null);

    [Fact]
    public void FuzzyMatcher_PrefersPrefix() =>
        Assert.True(FuzzyMatcher.Score("Ord", "OrderService.cs") > FuzzyMatcher.Score("Ord", "BigOrder.cs"));
}
