using LightweightIDE.Language.RoslynWorkspace;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.FindSymbols;
using Microsoft.CodeAnalysis.Rename;

namespace LightweightIDE.Language.Refactoring;

/// <summary>The symbol under the caret that would be renamed. <see cref="Error"/> is set when it cannot be renamed.</summary>
public sealed record RenameTarget(string Name, string Display, string Kind, string? Error);

/// <summary>New content for one file; <see cref="Changes"/> counts changed lines. <see cref="NewPath"/> is set when Roslyn suggests renaming the file with its type.</summary>
public sealed record FileEdit(string Path, string OldText, string NewText, int Changes, string? NewPath, bool IsNew = false);

public sealed record RenamePlan(string OldName, string NewName, IReadOnlyList<FileEdit> Files)
{
    public int Changes => Files.Sum(f => f.Changes);
}

/// <summary>Solution-wide rename with Roslyn's Renamer. It only computes the changes; the window applies them.</summary>
public sealed class RenameService(WorkspaceService workspace)
{
    public async Task<RenameTarget?> GetTargetAsync(string path, string text, int position, CancellationToken ct)
    {
        var (symbol, _) = await SymbolAtAsync(path, text, position, ct).ConfigureAwait(false);
        if (symbol is null) return null;
        var display = symbol.ToDisplayString(SymbolDisplayFormat.CSharpErrorMessageFormat);
        var kind = symbol.Kind == SymbolKind.NamedType ? ((INamedTypeSymbol)symbol).TypeKind.ToString().ToLowerInvariant() : symbol.Kind.ToString().ToLowerInvariant();
        string? error = null;
        if (!symbol.Locations.Any(l => l.IsInSource)) error = $"{display} is defined in a referenced assembly and cannot be renamed.";
        else if (symbol.IsImplicitlyDeclared) error = $"{display} is generated by the compiler.";
        else if (symbol.Locations.Any(l => l.IsInSource && IsGenerated(l.SourceTree?.FilePath))) error = $"{display} is declared in generated code.";
        return new RenameTarget(symbol.Name, display, kind, error);
    }

    /// <summary>Null when the name is a valid C# identifier (a keyword needs the @ prefix), otherwise the reason.</summary>
    public static string? ValidateName(string name)
    {
        if (string.IsNullOrWhiteSpace(name)) return "Enter a name.";
        var bare = name.StartsWith('@') ? name[1..] : name;
        if (!SyntaxFacts.IsValidIdentifier(bare)) return $"'{name}' is not a valid C# identifier.";
        if (!name.StartsWith('@') && (SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None || SyntaxFacts.GetContextualKeywordKind(name) is SyntaxKind.VarKeyword))
            return $"'{name}' is a keyword. Use @{name} to use it as an identifier.";
        return null;
    }

    public async Task<RenamePlan> PlanAsync(string path, string text, int position, string newName, CancellationToken ct)
    {
        if (ValidateName(newName) is { } invalid) throw new ArgumentException(invalid, nameof(newName));
        var (symbol, document) = await SymbolAtAsync(path, text, position, ct).ConfigureAwait(false);
        if (symbol is null) throw new InvalidOperationException("No symbol under the caret.");
        var solution = document.Project.Solution;
        // The file follows only a type whose name it carries (Calculator.cs for class Calculator).
        var renameFile = symbol is INamedTypeSymbol;
        var options = new SymbolRenameOptions(RenameOverloads: false, RenameInStrings: false, RenameInComments: false, RenameFile: renameFile);
        var renamed = await Renamer.RenameSymbolAsync(solution, symbol, options, newName, ct).ConfigureAwait(false);

        var files = new Dictionary<string, FileEdit>(StringComparer.Ordinal);
        foreach (var project in renamed.GetChanges(solution).GetProjectChanges())
        {
            foreach (var id in project.GetChangedDocuments(onlyGetDocumentsWithTextChanges: false))
            {
                var before = solution.GetDocument(id);
                var after = renamed.GetDocument(id);
                if (before?.FilePath is not { } filePath || after is null) continue;
                // Multi-targeted projects contain the same file several times.
                if (files.ContainsKey(filePath)) continue;
                var oldText = await before.GetTextAsync(ct).ConfigureAwait(false);
                var newText = await after.GetTextAsync(ct).ConfigureAwait(false);
                var changes = ChangedLines(oldText.ToString(), newText.ToString());
                var newPath = renameFile && after.Name != before.Name
                    && string.Equals(System.IO.Path.GetFileNameWithoutExtension(filePath), symbol.Name, StringComparison.Ordinal)
                        ? System.IO.Path.Combine(System.IO.Path.GetDirectoryName(filePath)!, after.Name)
                        : null;
                if (changes == 0 && newPath is null) continue;
                files[filePath] = new FileEdit(filePath, oldText.ToString(), newText.ToString(), changes, newPath);
            }
        }
        return new RenamePlan(symbol.Name, newName, files.Values.OrderBy(f => f.Path, StringComparer.Ordinal).ToList());
    }

    async Task<(ISymbol? Symbol, Document Document)> SymbolAtAsync(string path, string text, int position, CancellationToken ct)
    {
        var document = workspace.GetDocumentOrMisc(path, text);
        var model = await document.GetSemanticModelAsync(ct).ConfigureAwait(false);
        var symbol = await SymbolFinder.FindSymbolAtPositionAsync(model!, position, document.Project.Solution.Workspace, ct).ConfigureAwait(false);
        // Renaming a constructor or destructor means renaming its type.
        if (symbol is IMethodSymbol { MethodKind: MethodKind.Constructor or MethodKind.StaticConstructor or MethodKind.Destructor } method)
            symbol = method.ContainingType;
        return (symbol, document);
    }

    /// <summary>Rename never adds or removes lines, so lines are compared pairwise.</summary>
    static int ChangedLines(string oldText, string newText)
    {
        var a = oldText.Split('\n');
        var b = newText.Split('\n');
        return a.Length == b.Length ? a.Zip(b).Count(p => p.First != p.Second) : Formatting.TextDiff.Compute(oldText, newText).Count;
    }

    static bool IsGenerated(string? path) =>
        path is not null && (path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase) || path.EndsWith(".designer.cs", StringComparison.OrdinalIgnoreCase)
            || path.Contains("/obj/", StringComparison.Ordinal));
}
